// Writes packages/contracts/openapi.yaml from the Zod schemas.
// `--check` fails (exit 1) if the committed file is out of date — used in CI.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { stringify } from 'yaml';
import { generateOpenApiDocument } from '../src/openapi.ts';

const outPath = fileURLToPath(new URL('../openapi.yaml', import.meta.url));
const header = '# GENERATED by packages/contracts/scripts/generate-openapi.ts — do not edit by hand.\n';
const next = header + stringify(generateOpenApiDocument(), { lineWidth: 0 });

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outPath, 'utf8');
  } catch {
    // missing file counts as out of date
  }
  if (current !== next) {
    console.error('openapi.yaml is out of date. Run `pnpm openapi`.');
    process.exit(1);
  }
  console.warn('openapi.yaml is up to date.');
} else {
  writeFileSync(outPath, next);
  console.warn(`Wrote ${outPath}`);
}
