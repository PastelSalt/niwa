// Writes flutter_app/lib/core/theme/tokens.g.dart from the design tokens (specs §10.1: one token source).
// `--check` fails (exit 1) if the committed file is out of date — used in CI.
// Output is already `dart format`-clean so the Flutter format check passes without running Dart.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { palettes, shape, spacingUnit, typeColors, typography, type ColorMode } from '../src/index.ts';

const outPath = fileURLToPath(new URL('../../../flutter_app/lib/core/theme/tokens.g.dart', import.meta.url));

/** `#rrggbb` → `Color(0xFFRRGGBB)`. */
function color(hex: string): string {
  if (!/^#[0-9a-fA-F]{6}$/.test(hex)) throw new Error(`Not a #rrggbb colour: ${hex}`);
  return `Color(0xFF${hex.slice(1).toUpperCase()})`;
}

// CSS generics and desktop system fonts mean nothing on a phone; the platform default covers them.
const skipFamilies = new Set([
  'system-ui',
  '-apple-system',
  'Segoe UI',
  'sans-serif',
  'serif',
  'ui-monospace',
  'monospace',
]);
function families(css: string): string[] {
  return css
    .split(',')
    .map((f) => f.trim().replace(/^"|"$/g, ''))
    .filter((f) => f && !skipFamilies.has(f));
}

function dartString(s: string): string {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

const paletteFields = Object.keys(palettes.light) as (keyof (typeof palettes)['light'])[];
const typeFields = Object.keys(typeColors.light) as (keyof (typeof typeColors)['light'])[];

function dataClass(name: string, doc: string, fields: string[]): string {
  return [
    `/// ${doc}`,
    `class ${name} {`,
    '  const new({',
    ...fields.map((f) => `    required this.${f},`),
    '  });',
    '',
    ...fields.map((f) => `  final Color ${f};`),
    '}',
  ].join('\n');
}

function instance(type: string, name: string, values: object): string {
  return [
    `  static const ${type} ${name} = ${type}(`,
    ...Object.entries(values as Record<string, string>).map(([k, v]) => `    ${k}: ${color(v)},`),
    '  );',
  ].join('\n');
}

function stringList(name: string, values: string[]): string {
  const oneLine = `  static const List<String> ${name} = [${values.map(dartString).join(', ')}];`;
  if (oneLine.length <= 80) return oneLine;
  return [
    `  static const List<String> ${name} = [`,
    ...values.map((v) => `    ${dartString(v)},`),
    '  ];',
  ].join('\n');
}

const modes: ColorMode[] = ['light', 'dark'];

const next = [
  '// GENERATED by packages/tokens/scripts/generate-dart.ts — do not edit by hand.',
  '// Source: packages/tokens/src/index.ts. Regenerate with `pnpm tokens:dart`.',
  '',
  "import 'dart:ui' show Color;",
  '',
  dataClass('NiwaPalette', 'Colour roles for one mode (light or dark).', paletteFields),
  '',
  dataClass('NiwaTypeColors', 'Item-type accents (tree icons, scheduler blocks).', typeFields),
  '',
  'abstract final class NiwaTokens {',
  modes.map((m) => instance('NiwaPalette', m, palettes[m])).join('\n\n'),
  '',
  modes.map((m) => instance('NiwaTypeColors', `${m}Types`, typeColors[m])).join('\n\n'),
  '',
  stringList('fontFamilies', families(typography.fontFamily)),
  stringList('monoFamilies', families(typography.monoFamily)),
  `  static const double baseFontSize = ${typography.baseSize};`,
  `  static const double radius = ${shape.radius};`,
  `  static const double radiusSmall = ${shape.radiusSmall};`,
  '',
  '  /// 4px spacing grid.',
  `  static const double spacingUnit = ${spacingUnit};`,
  '}',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outPath, 'utf8');
  } catch {
    // missing file counts as out of date
  }
  if (current !== next) {
    console.error('tokens.g.dart is out of date. Run `pnpm tokens:dart`.');
    process.exit(1);
  }
  console.warn('tokens.g.dart is up to date.');
} else {
  writeFileSync(outPath, next);
  console.warn(`Wrote ${outPath}`);
}
